"""public/data/manifest.json: one entry per prepared dataset, read by src/data/manifest.ts."""

import hashlib
import json
from dataclasses import asdict, dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from .grid import GRIDS, GridSpec

MANIFEST_VERSION = 1


@dataclass(frozen=True)
class Source:
    name: str
    url: str
    license: str
    attribution: str


def _now() -> str:
    return datetime.now(UTC).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def _read(path: Path) -> dict[str, Any]:
    if path.exists():
        return json.loads(path.read_text(encoding="utf-8"))
    return {}


def record(
    output_dir: Path,
    dataset_id: str,
    file_name: str,
    *,
    format: str,
    sources: list[Source],
    grid: GridSpec | None = None,
    units: str | None = None,
    notes: str | None = None,
    stats: dict[str, Any] | None = None,
    layout: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Adds or replaces a dataset entry, keeping the other entries untouched."""
    file_path = output_dir / file_name
    data = file_path.read_bytes()
    entry: dict[str, Any] = {
        "path": file_name,
        "format": format,
        "bytes": len(data),
        "sha256": hashlib.sha256(data).hexdigest(),
        "generatedAt": _now(),
        "sources": [asdict(source) for source in sources],
    }
    if grid is not None:
        entry["grid"] = grid.id
    if units is not None:
        entry["units"] = units
    if notes is not None:
        entry["notes"] = notes
    if stats is not None:
        entry["stats"] = stats
    if layout is not None:
        entry["layout"] = layout

    manifest_path = output_dir / "manifest.json"
    manifest = _read(manifest_path)
    datasets: dict[str, Any] = manifest.get("datasets", {})
    datasets[dataset_id] = entry
    datasets = dict(sorted(datasets.items()))
    manifest = {
        "version": MANIFEST_VERSION,
        "grids": {spec.id: spec.to_manifest() for spec in GRIDS},
        "datasets": datasets,
    }
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", "utf-8")
    write_attribution(output_dir, datasets)
    return entry


def attribution_markdown(datasets: dict[str, Any]) -> str:
    lines = [
        "# Data attribution",
        "",
        "Generated by the quakeTrace pipeline from `manifest.json`; do not edit by hand.",
        "",
        "| Dataset | Source | License | Attribution |",
        "|---|---|---|---|",
    ]
    for dataset_id, entry in datasets.items():
        for source in entry["sources"]:
            lines.append(
                f"| `{dataset_id}` | [{source['name']}]({source['url']}) "
                f"| {source['license']} | {source['attribution']} |"
            )
    return "\n".join(lines) + "\n"


def write_attribution(output_dir: Path, datasets: dict[str, Any]) -> None:
    (output_dir / "ATTRIBUTION.md").write_text(attribution_markdown(datasets), "utf-8")
